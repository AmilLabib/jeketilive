// Regenerates src/data/members.ts from data/members.json, adding a photo per member
// (IDN avatar, falling back to the Showroom room image). IDN goes first because Showroom
// room covers aren't reliable, e.g. Michie's room cover is Levi's photo card.
import { readFile, writeFile } from 'node:fs/promises'

const members = JSON.parse(await readFile(new URL('../data/members.json', import.meta.url), 'utf8'))

async function showroomPhoto(roomId) {
  const res = await fetch(`https://www.showroom-live.com/api/room/profile?room_id=${roomId}`)
  if (!res.ok) return null
  const json = await res.json()
  return json.image_square || json.image || null
}

async function idnPhoto(username) {
  const res = await fetch('https://api.idn.app/graphql', {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      query: 'query ($u: String!) { getPublicProfileByUsername(username: $u) { avatar } }',
      variables: { u: username },
    }),
  })
  if (!res.ok) return null
  const json = await res.json()
  return json.data?.getPublicProfileByUsername?.avatar ?? null
}

const result = []
for (const member of members) {
  const photo =
    (member.idnUsername && (await idnPhoto(member.idnUsername))) ||
    (member.showroomId && (await showroomPhoto(member.showroomId))) ||
    null
  if (!photo) console.warn(`Foto tidak ditemukan: ${member.slug}`)
  result.push({ ...member, photo })
}

const source = `// Generated by scripts/sync-members.mjs. Edit data/members.json instead.
import type { Member } from '../lib/types'

export const members: Member[] = ${JSON.stringify(result, null, 2)}
`
await writeFile(new URL('../src/data/members.ts', import.meta.url), source)
console.log(`Wrote ${result.length} members`)
